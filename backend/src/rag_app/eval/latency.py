BEFORE_WARM_PATH = EVAL_DIR / "latency_before_warm.json"
WARM_VS_COLD_PATH = EVAL_DIR / "latency_warm_vs_cold.json"
CONCURRENCY_PATH = EVAL_DIR / "latency_concurrency.json"

RERANKER_MODES = ("fresh", "shared", "warm-single")

# N runs over the golden set (14 questions, 2026-10-02): each run pays a FRESH
# `CrossEncoderReranker()` load per question (today's bug) + a real Ollama generate +
# groundedness call per question. N=3 (42 answers total) keeps a local run in the
# few-minutes range (measured on the development machine, recorded below in the printed
# summary and in the written JSON's "runtime_s") while still giving p50/p95 some spread
# (42 samples: p95 is the ~40th-largest, not just the max).
DEFAULT_RUNS = 3

STAGE_NAMES = (
    "classify",
    "embed",
    "hybrid_search",
    "rerank_load",
    "rerank_inference",
    "generate",
    "groundedness",
    "ttft",
    "total",
)


@dataclass
class LatencyReport:
    machine: dict[str, object]
    n_runs: int
    n_questions: int
    runtime_s: float
    stages_ms: dict[str, dict[str, float]]  # stage -> {p50, p95, n, mean}

    def to_json(self) -> dict[str, object]:
        return {
            "machine": self.machine,
            "n_runs": self.n_runs,
            "n_questions": self.n_questions,
            "runtime_s": round(self.runtime_s, 1),
            "stages_ms": self.stages_ms,
        }


def _percentile(values: list[float], pct: float) -> float:
    """Nearest-rank percentile (no numpy dependency); ``values`` need not be pre-sorted."""
    if not values:
        return 0.0
    ordered = sorted(values)
    index = max(0, min(len(ordered) - 1, round(pct / 100 * (len(ordered) - 1))))
    return ordered[index]


def _git_sha() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            timeout=5,
            check=True,
        )
        return out.stdout.strip()
    except Exception:  # noqa: BLE001 - best effort, never fatal
        return "unknown"


def _gpu_info() -> str | None:
    try:
        out = subprocess.run(
            ["nvidia-smi", "--query-gpu=name,memory.total", "--format=csv,noheader"],
            capture_output=True,
            text=True,
            timeout=5,
            check=True,
        )
        line = out.stdout.strip().splitlines()
        return line[0] if line else None
    except Exception:  # noqa: BLE001 - no GPU / no driver is a normal case
        return None


def _cpu_model() -> str:
    try:
        text_ = Path("/proc/cpuinfo").read_text(encoding="utf-8")
        for line in text_.splitlines():
            if line.lower().startswith("model name"):
                return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or platform.machine()


def _ram_gib() -> float:
    try:
        page_size = os.sysconf("SC_PAGE_SIZE")
        pages = os.sysconf("SC_PHYS_PAGES")
        return (page_size * pages) / (1024**3)
    except (ValueError, OSError, AttributeError):
        return 0.0


def machine_info(*, reranker_device: str, reranker_mode: str = "shared") -> dict[str, object]:
    settings = get_settings()
    return {
        "cpu": _cpu_model(),
        "cpu_count": os.cpu_count(),
        "ram_gib": round(_ram_gib(), 1),
        "gpu": _gpu_info(),
        "reranker_device": reranker_device,
        "reranker_mode": reranker_mode,
        "llm_model": settings.llm_model,
        "embed_model": settings.embed_model,
        "reranker_model": settings.reranker_model,
        "reranker_revision": settings.reranker_revision,
        "top_k": settings.top_k,
        "rerank_top_n": settings.rerank_top_n,
        "num_ctx_answer": settings.num_ctx_answer,
        "num_ctx_groundedness": settings.num_ctx_groundedness,
        "commit": _git_sha(),
    }


def _reranker_factory(mode: str) -> Callable[[], CrossEncoderReranker]:
    """Zero-arg callable producing the ``CrossEncoderReranker`` instance ``retrieve`` should
    use for the NEXT question, per ``reranker_mode`` (see this module's docstring)."""
    from rag_app.reranking import CrossEncoderReranker, get_shared_reranker

    if mode == "fresh":
        return lambda: CrossEncoderReranker()
    if mode == "shared":
        reranker = get_shared_reranker()
    elif mode == "warm-single":
        reranker = CrossEncoderReranker()
    else:
        raise ValueError(f"unknown reranker_mode: {mode!r} (expected one of {RERANKER_MODES})")
    reranker.warm_up()  # pays rerank_load/first-inference ONCE, before the loop starts
    return lambda: reranker


def run_latency_benchmark(
    session: Session,
    items: list[GoldenItem],
    *,
    n_runs: int = DEFAULT_RUNS,
    reranker_device: str = "cpu",
    reranker_mode: str = "shared",
) -> LatencyReport:
    """Run the golden set ``n_runs`` times through the exact same calls
    ``generation.answer_question`` makes (``reranking.retrieve`` then
    ``answer_from_chunks``), collecting every stage duration via our OWN
    ``timing.recorder(on_stage=...)``. ``reranker_mode`` picks which reranker instance(s)
    the loop uses — see this module's docstring.

    Deliberately inlined rather than calling ``answer_question`` itself: that function opens
    its own recorder with the Prometheus ``observe_stage`` callback hard-wired (correct for
    the live API), and a recorder cannot be nested — an outer one here would never see any
    stage duration (`timing.stage()` always reports to the innermost active recorder).
    """
    from rag_app.generation import answer_from_chunks
    from rag_app.reranking import retrieve

    chat = OllamaChat()
    reranker_for = _reranker_factory(reranker_mode)
    durations_ms: dict[str, list[float]] = {name: [] for name in STAGE_NAMES}

    def on_stage(name: str, elapsed_s: float) -> None:
        durations_ms.setdefault(name, []).append(elapsed_s * 1000)

    start = time.perf_counter()
    for _ in range(n_runs):
        for item in items:
            with timing.recorder(streaming=False, on_stage=on_stage):
                chunks = retrieve(
                    session, item.question, reranker=reranker_for(), version=item.version
                )
                answer_from_chunks(chat, item.question, chunks)
    runtime_s = time.perf_counter() - start

    stages_ms: dict[str, dict[str, float]] = {}
    for name, values in durations_ms.items():
        if not values:
            continue
        stages_ms[name] = {
            "n": len(values),
            "mean": round(sum(values) / len(values), 1),
            "p50": round(_percentile(values, 50), 1),
            "p95": round(_percentile(values, 95), 1),
        }

    return LatencyReport(
        machine=machine_info(reranker_device=reranker_device, reranker_mode=reranker_mode),
        n_runs=n_runs,
        n_questions=len(items),
        runtime_s=runtime_s,
        stages_ms=stages_ms,
    )


def measure_warm_vs_cold(
    session: Session, item: GoldenItem, *, n_calls: int = 5
) -> dict[str, object]:
    """Warm-vs-cold sanity check (DA review of block C, checks 2 + 4): isolates "warm-up
    artifact removed" from "genuine per-token inference cost" by running ``.rerank()`` against
    the SAME real candidate pool several times in a row on a FRESH, NOT pre-warmed reranker
    instance. Call 1 pays ``rerank_load`` (model construction) and a first real forward pass;
    calls 2..N have no ``rerank_load`` (already constructed) and measure steady-state
    inference cost only."""
    from rag_app.reranking import CrossEncoderReranker
    from rag_app.retrieval import hybrid_search

    settings = get_settings()
    candidates = hybrid_search(
        session,
        item.question,
        top_k=settings.top_k,
        candidate_k=settings.top_k,
        version=item.version,
    )
    reranker = CrossEncoderReranker()

    calls: list[dict[str, object]] = []
    for i in range(n_calls):
        stage_ms: dict[str, float] = {}

        def on_stage(name: str, elapsed_s: float, stage_ms: dict[str, float] = stage_ms) -> None:
            stage_ms[name] = elapsed_s * 1000

        with timing.recorder(streaming=False, on_stage=on_stage):
            reranker.rerank(item.question, list(candidates), settings.rerank_top_n)
        calls.append(
            {
                "call": i + 1,
                "rerank_load_ms": round(stage_ms.get("rerank_load", 0.0), 1),
                "rerank_inference_ms": round(stage_ms.get("rerank_inference", 0.0), 1),
            }
        )

    later = calls[1:]
    later_inference_ms: list[float] = [float(c["rerank_inference_ms"]) for c in later]  # type: ignore[arg-type]
    later_mean = round(sum(later_inference_ms) / len(later_inference_ms), 1) if later else 0.0
    return {
        "n_candidates": len(candidates),
        "first_call": calls[0],
        "later_calls": later,
        "later_mean_inference_ms": later_mean,
    }


def measure_concurrency(
    session_factory: object, items: list[GoldenItem], *, concurrency: int
) -> dict[str, object]:
    """``rerank_inference`` latency when ``concurrency`` threads call the SAME shared, warmed
    reranker at once (DA-11bC-2: real concurrent ``/chat``-shaped traffic contends for the
    same CPU model instead of running alone). Each thread loops over the full golden set
    once; `rerank_inference` durations from every thread are pooled into one p50/p95."""
    from rag_app.reranking import get_shared_reranker, retrieve

    reranker = get_shared_reranker()
    reranker.warm_up()

    durations_ms: list[float] = []
    lock = threading.Lock()
    errors: list[BaseException] = []

    def worker() -> None:
        with session_factory() as session:  # type: ignore[operator]
            for item in items:

                def on_stage(name: str, elapsed_s: float) -> None:
                    if name == "rerank_inference":
                        with lock:
                            durations_ms.append(elapsed_s * 1000)

                try:
                    with timing.recorder(streaming=False, on_stage=on_stage):
                        retrieve(session, item.question, reranker=reranker, version=item.version)
                except BaseException as exc:  # noqa: BLE001 - surfaced after join()
                    with lock:
                        errors.append(exc)

    threads = [threading.Thread(target=worker) for _ in range(concurrency)]
    start = time.perf_counter()
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    wall_s = time.perf_counter() - start

    if errors:
        raise errors[0]

    return {
        "concurrency": concurrency,
        "n": len(durations_ms),
        "p50": round(_percentile(durations_ms, 50), 1),
        "p95": round(_percentile(durations_ms, 95), 1),
        "wall_s": round(wall_s, 1),
    }


def _stack_available() -> bool:
    settings = get_settings()
    try:
        with make_engine().connect() as conn:
            conn.execute(text("SELECT 1"))
    except Exception:  # noqa: BLE001
        return False
    try:
        httpx.get(f"{settings.ollama_host.rstrip('/')}/api/tags", timeout=5).raise_for_status()
    except Exception:  # noqa: BLE001
        return False
    return True


def _print_summary(report: LatencyReport) -> None:
    print(f"\nlatency baseline: {report.n_runs} run(s) x {report.n_questions} question(s)")
    print(f"machine: {report.machine}")
    header = f"{'stage':18} {'n':>4} {'mean_ms':>10} {'p50_ms':>10} {'p95_ms':>10}"
    print(header)
    for name in STAGE_NAMES:
        stats = report.stages_ms.get(name)
        if not stats:
            continue
        print(
            f"{name:18} {stats['n']:>4.0f} {stats['mean']:>10.1f}"
            f" {stats['p50']:>10.1f} {stats['p95']:>10.1f}"
        )
    print(f"runtime: {report.runtime_s:.1f} s\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Record p50/p95 latency per stage.")
    parser.add_argument("--golden", type=Path, default=DEFAULT_GOLDEN_SET)
    parser.add_argument("--runs", type=int, default=DEFAULT_RUNS)
    parser.add_argument(
        "--device",
        choices=("cpu", "gpu"),
        default="cpu",
        help="reranker device label; 'cpu' also hides CUDA from torch before any model loads"
        " (Azure-relevant number) — a no-op with this repo's CURRENT CPU-only torch pin"
        " (requirements-torch.txt), kept for when T11.5.1's experiment matrix adds a GPU"
        " variant; 'gpu' leaves CUDA visible (local-dev-only number once that lands)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="defaults to latency_results.json, or latency_baseline.json with"
        " --update-baseline (same split as eval.gate's results.json/baseline_metrics.json)",
    )
    parser.add_argument(
        "--update-baseline",
        action="store_true",
        help="write/overwrite the git-tracked latency_baseline.json (do this on purpose, not"
        " on every gate run — otherwise timing jitter would dirty the tree on every --full)",
    )
    parser.add_argument(
        "--require-stack",
        action="store_true",
        help="fail (instead of skipping) when Postgres/Ollama are not reachable (gate --full)",
    )
    parser.add_argument(
        "--reranker-mode",
        choices=RERANKER_MODES,
        default="shared",
        help="'shared' (default, routine/gate run): the real warmed singleton, genuine"
        " steady-state cost; 'fresh': a new instance per question (today's reload bug — only"
        " to reproduce the committed baseline's methodology on request, never writes over"
        " it); 'warm-single': a throwaway warmed instance, the 'before, warm' reference",
    )
    parser.add_argument(
        "--warm-vs-cold",
        action="store_true",
        help="run the warm-vs-cold sanity check instead of the normal benchmark (DA review"
        " of block C): first predict() on a fresh instance vs later, already-warm calls on"
        " the SAME instance; writes latency_warm_vs_cold.json (git-ignored)",
    )
    parser.add_argument(
        "--concurrency",
        type=int,
        default=0,
        help="run the concurrency contention check instead of the normal benchmark"
        " (DA-11bC-2): N threads call the shared, warmed reranker at once; writes"
        " latency_concurrency.json (git-ignored)",
    )
    args = parser.parse_args(argv)
    out_path = args.out or (BASELINE_PATH if args.update_baseline else RESULTS_PATH)

    if args.device == "cpu":
        # Must happen before any torch import (lazy, inside reranking.load_cross_encoder) —
        # argparse runs first, so this is still early enough.
        os.environ["CUDA_VISIBLE_DEVICES"] = ""

    if not _stack_available():
        if args.require_stack:
            settings = get_settings()
            print(
                "latency gate: FAIL — stack not reachable (Postgres or Ollama at"
                f" {settings.ollama_host}); start it or fix OLLAMA_HOST / DATABASE_URL",
                file=sys.stderr,
            )
            return 1
        print("latency gate: SKIP (Postgres/Ollama not reachable)")
        return 0

    items = load_golden_set(args.golden)
    session_factory = make_session_factory()

    if args.concurrency:
        result = measure_concurrency(session_factory, items, concurrency=args.concurrency)
        print(f"\nconcurrency check: {result}")
        EVAL_DIR.mkdir(parents=True, exist_ok=True)
        CONCURRENCY_PATH.write_text(json.dumps(result, indent=2, sort_keys=True), encoding="utf-8")
        print(f"latency concurrency written -> {CONCURRENCY_PATH}")
        return 0

    if args.warm_vs_cold:
        with session_factory() as session:
            result = measure_warm_vs_cold(session, items[0])
        print(f"\nwarm-vs-cold check: {result}")
        EVAL_DIR.mkdir(parents=True, exist_ok=True)
        WARM_VS_COLD_PATH.write_text(json.dumps(result, indent=2, sort_keys=True), encoding="utf-8")
        print(f"latency warm-vs-cold written -> {WARM_VS_COLD_PATH}")
        return 0

    with session_factory() as session:
        report = run_latency_benchmark(
            session,
            items,
            n_runs=args.runs,
            reranker_device=args.device,
            reranker_mode=args.reranker_mode,
        )

    _print_summary(report)

    EVAL_DIR.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(report.to_json(), indent=2, sort_keys=True), encoding="utf-8")
    label = "baseline" if args.update_baseline else "results"
    print(f"latency {label} written -> {out_path}")
    print("\nLATENCY GATE: RECORDED (no pass/fail threshold yet — T11.6b.1)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
