"""p50/p95 latency per stage over the golden set — the "before" baseline (T11.3.5) and the
"after"/routine measurement (T11.4.4, block E).

Drives the same calls ``generation.answer_question`` makes, once per golden item per run,
through ``reranking.retrieve`` + ``generation.answer_from_chunks``. The reranker instance used
for the loop is controlled by ``reranker_mode`` (T11.4.4, block E DA review on block C):

- ``"fresh"`` — a brand-new ``CrossEncoderReranker()`` per question, today's reload-per-
  request bug included. This is EXACTLY what produced the committed, frozen
  ``eval/latency_baseline.json`` ("before") and is kept available (not run by default) only
  to reproduce that file's methodology on request — the committed baseline itself is never
  regenerated by a routine run.
- ``"shared"`` (the default, routine/gate run) — the real process-wide
  ``reranking.get_shared_reranker()``, warmed once before the loop exactly like the FastAPI
  lifespan does, then reused for every question: the "after" number, reflecting genuine
  production steady-state cost instead of a fresh-instance warm-up artifact repeated on every
  sample (DA review of block C, check 4).
- ``"warm-single"`` — a throwaway instance of the SAME class, warmed once the same way, but
  NOT the production singleton: an honest "before, warm" reference (today's reranker/`top_k`,
  with the reload tax removed) for the ADR, isolated from the DI wiring itself. Numerically
  close to "shared" until T11.5 actually changes the reranker/`top_k`.

Deliberately excludes the correctness judge (an extra, non-user-facing LLM call that would
also contend for the GPU/CPU and pollute the numbers — ``eval.benchmark`` notes the same
exclusion).

Per-stage durations come from the same ``rag_app.timing`` recorder the live API uses (an
``on_stage`` callback appends every stage/ttft/total duration), so a number here means
exactly the same thing as a number in the Prometheus histograms or the `answer_timing` log
line.

Writes ``eval/latency_baseline.json`` only with ``--update-baseline`` (never by a routine
run): machine/model details (CPU, GPU, RAM, model names + revisions, reranker device,
`top_k`/`rerank_top_n`, git commit, `reranker_mode`) alongside p50/p95 per stage, so a number
is never compared across machines, configurations or reranker modes by accident. A routine
run writes the git-ignored ``latency_results.json`` instead; ``--warm-vs-cold`` and
``--concurrency`` write their own git-ignored files (see ``main()``).

Called by ``scripts/gate.sh`` (step ``latency``) with ``--require-stack``. This block
(T11.3.5/T11.4.4) only RECORDS — no pass/fail threshold yet (T11.6b.1, block G, compares a
later run against the file an earlier block "adopts" as the baseline).
"""

